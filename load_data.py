# 4. DB 연결 및 데이터 적재
conn = mysql.connector.connect(**DB_CONFIG)
cursor = conn.cursor()

insert_sql = """
INSERT INTO yokai_compendium (
    name, country, saju_element, plutchik_dyad, plutchik_ko,
    valence, arousal, narrative_dialogue, micro_action, story, source_url
) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
"""

success_count = 0
for idx, row in df.iterrows():
  name = row["요괴이름"]
  country = row["국가"]
  story = row["괴담내용"]
  source_url = row["출처URL"] if pd.notna(row["출처URL"]) else None

  # 인덱스 기준 매핑 데이터 추출
  m = YOKAI_METRICS[idx]
  saju_element = m[0]
  plutchik_dyad = m[1]
  plutchik_ko = m[2]
  valence = m[3]
  arousal = m[4]
  narrative_dialogue = m[5]
  micro_action = m[6]

  values = (
      name,
      country,
      saju_element,
      plutchik_dyad,
      plutchik_ko,
      valence,
      arousal,
      narrative_dialogue,
      micro_action,
      story,
      source_url,
  )

  cursor.execute(insert_sql, values)
  success_count += 1

conn.commit()
cursor.close()
conn.close()

print(
    f"\nDB 적재 완료: 총 {success_count}건의 요괴 데이터가 성공적으로"
    " 저장되었습니다!"
)